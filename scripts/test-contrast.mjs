/**
 * Contrast guardrail.
 *
 * Resolves every semantic alias to a concrete colour in both themes, measures
 * the pairs the system actually puts on screen, and fails the build on any
 * regression. Known failures live in knowledge/contrast-exceptions.json with a
 * reason and an owner, so an exception is a decision on the record rather than
 * a silence.
 *
 * Run `node scripts/test-contrast.mjs --report` to print the full matrix.
 */
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { contrastRatio, flatten, round, THRESHOLDS, wcagLabel } from './color.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(ROOT, 'tokens/tokens.source.json'), 'utf8'));
const REPORT = process.argv.includes('--report');

const primitive = (name) => src.primitives.find((t) => t.name === name)?.value;
const alias = (name) => src.aliases.find((a) => a.name === name);

/** Concrete hex for an alias in a theme, flattened over that theme's page ground. */
const resolve = (name, mode) => {
  const a = alias(name);
  if (!a) throw new Error(`unknown alias: ${name}`);
  const { ref, alpha } = a[mode];
  const base = ref.startsWith('#') ? ref : primitive(ref);
  if (!base) throw new Error(`unknown primitive: ${ref}`);
  if (alpha >= 1) return base.toUpperCase();
  const groundRef = alias('surface-page')[mode].ref;
  const ground = groundRef.startsWith('#') ? groundRef : primitive(groundRef);
  return flatten(base, alpha, ground);
};

/**
 * The pairs this system puts on screen. `kind` selects the WCAG threshold:
 * normal text 4.5, large text 3, non-text UI 3.
 */
const PAIRS = [
  // Body and heading copy on each ground
  { fg: 'text-primary', bg: 'surface-page', kind: 'normal', where: 'Body and headings on the page ground' },
  { fg: 'text-primary', bg: 'surface-raised', kind: 'normal', where: 'Copy inside cards and panels' },
  { fg: 'text-primary', bg: 'surface-brand', kind: 'normal', where: 'Copy on the tinted brand section' },
  { fg: 'text-secondary', bg: 'surface-page', kind: 'normal', where: 'Supporting copy on the page ground' },
  { fg: 'text-secondary', bg: 'surface-raised', kind: 'normal', where: 'Supporting copy inside cards' },
  { fg: 'text-muted', bg: 'surface-page', kind: 'normal', where: 'System labels and metadata' },
  { fg: 'text-muted', bg: 'surface-raised', kind: 'normal', where: 'Table headers and captions' },
  { fg: 'text-brand', bg: 'surface-page', kind: 'normal', where: 'Links and token names' },
  { fg: 'text-brand', bg: 'surface-brand', kind: 'normal', where: 'Links inside a tinted section' },
  { fg: 'text-brand', bg: 'surface-raised', kind: 'normal', where: 'Links inside a card' },

  // Actions
  { fg: 'action-primary-fg', bg: 'action-primary', kind: 'normal', where: 'Label on the primary CTA' },
  { fg: 'text-brand', bg: 'surface-page', kind: 'ui', where: 'Secondary CTA outline against the page' },

  // Non-text UI
  { fg: 'border-brand', bg: 'surface-page', kind: 'ui', where: 'Component outlines, label pills' },
  { fg: 'border-subtle', bg: 'surface-page', kind: 'ui', where: 'Hairlines and table rules' },
  { fg: 'focus-ring', bg: 'surface-page', kind: 'ui', where: 'Focus outline on the page ground' },
  { fg: 'focus-ring', bg: 'surface-raised', kind: 'ui', where: 'Focus outline inside a card' },

  // The one contextual accent
  { fg: 'accent-ai-fg', bg: 'accent-ai', kind: 'normal', where: 'Ink label on the bright GenAI fill' },
  { fg: 'accent-ai-strong', bg: 'surface-page', kind: 'ui', where: 'GenAI CTA boundary against the page' }
];

const exceptionsPath = join(ROOT, 'knowledge/contrast-exceptions.json');
const exceptions = existsSync(exceptionsPath)
  ? JSON.parse(readFileSync(exceptionsPath, 'utf8')).exceptions
  : [];

const keyOf = (p, mode) => `${p.fg} on ${p.bg} (${mode}, ${p.kind})`;
const exceptionFor = (key) => exceptions.find((e) => e.pair === key);

const results = [];
for (const mode of ['light', 'dark']) {
  for (const p of PAIRS) {
    const fg = resolve(p.fg, mode);
    const bg = resolve(p.bg, mode);
    const ratio = round(contrastRatio(fg, bg));
    const need = THRESHOLDS[p.kind];
    const key = keyOf(p, mode);
    results.push({
      key, mode, kind: p.kind, where: p.where,
      fgToken: p.fg, bgToken: p.bg,
      fg, bg, ratio, need,
      pass: ratio >= need,
      exception: exceptionFor(key)
    });
  }
}

/**
 * The matrix is written to disk on every run and committed. A token change then
 * shows up in review as a contrast diff, which is the point: the numbers move
 * in the same pull request as the value that moved them.
 */
const matrix = [
  '# Assembly contrast matrix',
  '',
  '<!-- Generated by scripts/test-contrast.mjs. Do not edit by hand. -->',
  '',
  `Measured ${new Date().toISOString().slice(0, 10)} against WCAG 2.1. Normal text needs 4.5:1, large text and non-text UI need 3:1.`,
  '',
  'Alpha values are flattened over the page ground of their own theme before measuring, so these are the ratios that reach the eye rather than the ratios the token declares.',
  ''
];
for (const mode of ['light', 'dark']) {
  matrix.push(`## ${mode[0].toUpperCase() + mode.slice(1)} theme`, '');
  matrix.push('| Pair | Kind | Foreground | Background | Ratio | Needs | WCAG | Result |');
  matrix.push('| --- | --- | --- | --- | ---: | ---: | --- | --- |');
  for (const r of results.filter((x) => x.mode === mode)) {
    const verdict = r.pass ? 'pass' : r.exception ? `excepted (${r.exception.severity})` : '**FAIL**';
    matrix.push(`| \`${r.fgToken}\` on \`${r.bgToken}\` | ${r.kind} | ${r.fg} | ${r.bg} | ${r.ratio}:1 | ${r.need}:1 | ${wcagLabel(r.ratio)} | ${verdict} |`);
  }
  matrix.push('');
}
matrix.push('## Where each pair appears', '');
for (const p of PAIRS) matrix.push(`- \`${p.fg}\` on \`${p.bg}\` (${p.kind}): ${p.where}`);
matrix.push('');
writeFileSync(join(ROOT, 'knowledge/contrast-matrix.md'), matrix.join('\n'));

if (REPORT) {
  for (const mode of ['light', 'dark']) {
    console.log(`\n${mode.toUpperCase()}\n${'-'.repeat(96)}`);
    console.log(
      'PAIR'.padEnd(42) + 'FG'.padEnd(10) + 'BG'.padEnd(10) +
      'RATIO'.padStart(7) + 'NEED'.padStart(6) + '  ' + 'WCAG'.padEnd(14) + 'RESULT'
    );
    for (const r of results.filter((x) => x.mode === mode)) {
      console.log(
        `${r.fgToken} on ${r.bgToken} [${r.kind}]`.padEnd(42) +
        r.fg.padEnd(10) + r.bg.padEnd(10) +
        String(r.ratio).padStart(7) + String(r.need).padStart(6) + '  ' +
        wcagLabel(r.ratio).padEnd(14) +
        (r.pass ? 'pass' : r.exception ? 'fail (excepted)' : 'FAIL')
      );
    }
  }
  console.log();
}

const failures = results.filter((r) => !r.pass && !r.exception);
const excepted = results.filter((r) => !r.pass && r.exception);
const stale = exceptions.filter((e) => {
  const r = results.find((x) => x.key === e.pair);
  return !r || r.pass;
});

console.log(`contrast: ${results.length - failures.length - excepted.length} pass, ` +
  `${excepted.length} excepted, ${failures.length} fail`);

for (const e of excepted) {
  console.log(`  excepted  ${e.key} = ${e.ratio}:1 (needs ${e.need}) :: ${e.exception.reason}`);
}
for (const s of stale) {
  console.log(`  stale exception, now passing or removed: ${s.pair}`);
}
for (const f of failures) {
  console.log(`  FAIL      ${f.key} = ${f.ratio}:1 (needs ${f.need}) :: ${f.where}`);
  console.log(`            ${f.fg} on ${f.bg}`);
}

if (failures.length) {
  console.error(`\n${failures.length} contrast failure(s). Fix the token, or record an exception in knowledge/contrast-exceptions.json with a reason and an owner.`);
  process.exit(1);
}
if (stale.length) {
  console.error(`\n${stale.length} stale exception(s). Remove them from knowledge/contrast-exceptions.json.`);
  process.exit(1);
}
